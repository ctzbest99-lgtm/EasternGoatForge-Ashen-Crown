#!/usr/bin/env python3
"""Generate scr_dialogue_data_ch6.gml from docs/story/CHAPTER6_SCRIPT.md (approved 2026-11-16).

Every **ID** · Speaker line with a > quote below it becomes one node (text verbatim).
NARRATION -> speaker "" (no name in the box), as in Chapters 1-5.

Also writes the gamemaker mirror (gamemaker/scripts/scr_dialogue_data_ch6/) and adds the
script to AshenCrown.yyp if it is not registered yet. Re-run after script edits:
    python3 tools/gen_ch6_dialogue.py
"""
import json, re, os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "docs/story/CHAPTER6_SCRIPT.md")
OUT = os.path.join(ROOT, "game/scripts/scr_dialogue_data_ch6.gml")
GM = os.path.join(ROOT, "gamemaker")
NAME = "scr_dialogue_data_ch6"

hdr = re.compile(r'^(?:.*?[,—] )?\*\*([A-Z][A-Z0-9_]+)\*\*\s*·\s*(.+?):?$')
nodes, cur = [], None
for line in open(SRC, encoding="utf-8").read().split("\n"):
    m = hdr.match(line)
    if m:
        sp = re.sub(r'\*\*\[.*$', '', m.group(2)).strip()
        sp = re.sub(r'\*\(.*?\)\*', '', sp).strip(' *')
        cur = {"id": m.group(1), "speaker": sp, "lines": []}
        nodes.append(cur)
        continue
    if cur is None:
        continue
    if line.startswith(">"):
        t = line[1:].strip()
        if t:
            cur["lines"].append(t)
    elif line.strip() and cur["lines"]:
        cur = None

# Lines the wiring needs that the script does not carry (repeat talk, the fight prompt, the
# chapter card). Tagged PLACEHOLDER in the output; change freely.
EXTRA = [
    {"id": "BW_STONE_R1", "speaker": "NARRATION",
     "lines": ["The mark is cut shallow. Whoever made it wanted it read once."]},
    {"id": "CH_BERRIN_R1", "speaker": "Berrin",
     "lines": ["Ask the wood. I've told you what I'll tell you."]},
    {"id": "PT_CAMP_R1", "speaker": "NARRATION",
     "lines": ["The camp is as you left it. Nobody has come for the armour."]},
    {"id": "BH_FIGHT_01", "speaker": "NARRATION",
     "lines": ["The thorn moves before you are ready for it."]},
    {"id": "BH_FIGHT_02", "speaker": "SYSTEM",
     "lines": ["The Burn-Line Hulk. Boss."]},
    {"id": "CH_END_02", "speaker": "SYSTEM",
     "lines": ["Quest updated: Find out what Cinderhollow pays, and to whom.",
               "Chapter 6 — The Green Silence — Complete."]},
]


def q(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


out = []
out.append('/// scr_dialogue_data_ch6 — Chapter 6 dialogue nodes, keyed by the line ids in')
out.append('/// docs/story/CHAPTER6_SCRIPT.md (approved Nov 16 2026). Text is verbatim.')
out.append('/// GENERATED by tools/gen_ch6_dialogue.py — edit the script and re-run, do not hand-edit.')
out.append('/// Speaker "" is NARRATION. The last block holds the wiring pass\'s placeholder lines (not in the script).')
out.append("")
out.append("function scr_ch6_dialogue_node(_id) {")
out.append("    switch (_id) {")
seen = set()
for n in nodes + [dict(e, extra=True) for e in EXTRA]:
    if n["id"] in seen or not n["lines"]:
        continue
    seen.add(n["id"])
    sp = "" if n["speaker"] == "NARRATION" else n["speaker"]
    tag = "  // PLACEHOLDER (wiring pass, not in the script)" if n.get("extra") else ""
    out.append("        case %s:%s" % (q(n["id"]), tag))
    out.append("            return { id: %s, speaker: %s, lines: [%s] };" % (
        q(n["id"]), q(sp), ", ".join(q(l) for l in n["lines"])))
out.append("    }")
out.append("    return undefined;")
out.append("}")
out.append("")
text = "\n".join(out)
with open(OUT, "w", encoding="utf-8", newline="\n") as f:
    f.write(text)

gdir = os.path.join(GM, "scripts", NAME)
os.makedirs(gdir, exist_ok=True)
with open(os.path.join(gdir, NAME + ".gml"), "w", encoding="utf-8", newline="\n") as f:
    f.write(text)
with open(os.path.join(gdir, NAME + ".yy"), "w", encoding="utf-8", newline="\n") as f:
    json.dump({
        "$GMScript": "v1", "%Name": NAME, "isCompatibility": False, "isDnd": False,
        "name": NAME, "parent": {"name": "scripts", "path": "folders/scripts.yy"},
        "resourceType": "GMScript", "resourceVersion": "2.0",
    }, f, indent=2)
    f.write("\n")

yyp_path = os.path.join(GM, "AshenCrown.yyp")
yyp = open(yyp_path, encoding="utf-8").read()
if '"name":"%s"' % NAME not in yyp:
    anchor = ('    {\n      "id":{\n        "name":"rm_hollow_approach",\n'
              '        "path":"rooms/rm_hollow_approach/rm_hollow_approach.yy",\n      },\n    },\n')
    assert anchor in yyp, "yyp anchor for the resource list not found"
    block = ('    {\n      "id":{\n        "name":"%s",\n'
             '        "path":"scripts/%s/%s.yy",\n      },\n    },\n') % (NAME, NAME, NAME)
    yyp = yyp.replace(anchor, block + anchor, 1)
    with open(yyp_path, "w", encoding="utf-8", newline="\n") as f:
        f.write(yyp)
    print("registered", NAME, "in the yyp")
else:
    print(NAME, "already registered")

print("wrote", OUT, len(seen), "nodes")
