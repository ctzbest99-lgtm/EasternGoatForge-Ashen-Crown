#!/usr/bin/env python3
"""Generate game/scripts/scr_dialogue_data_ch3.gml from docs/story/CHAPTER3_SCRIPT.md.

Every **ID** · Speaker line with a > quote below it becomes one node (text verbatim).
NARRATION -> speaker "" (no name in the box), as in Chapters 1-2. Re-run after edits:
    python3 tools/gen_ch3_dialogue.py
"""
import re, os
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "docs/story/CHAPTER3_SCRIPT.md")
OUT = os.path.join(ROOT, "game/scripts/scr_dialogue_data_ch3.gml")

hdr = re.compile(r'^(?:.*?[,—] )?\*\*([A-Z][A-Z0-9_]+)\*\*\s*·\s*(.+?):?$')
nodes, cur = [], None
for line in open(SRC, encoding="utf-8").read().split("\n"):
    m = hdr.match(line)
    if m:
        sp = re.sub(r'\*\*\[.*$', '', m.group(2)).strip()
        sp = re.sub(r'\*\(.*?\)\*', '', sp).strip(' *')
        cur = {"id": m.group(1), "speaker": sp, "lines": []}
        nodes.append(cur)
        continue
    if cur is None:
        continue
    if line.startswith(">"):
        t = line[1:].strip()
        if t:
            cur["lines"].append(t)
    elif line.strip() and cur["lines"]:
        cur = None

# Lines the map/wiring pass needs that the script does not carry (room dressing,
# locked doors, inspect spots). Clearly tagged; change freely.
EXTRA = [
    {"id": "VR_WEST_SIGN", "speaker": "NARRATION", "lines": ["West country road. Hills by sundown tomorrow, if you don't linger."]},
    {"id": "VM_SALT_SIGN", "speaker": "NARRATION", "lines": ["A lamp above the door, crusted white with salt.", "The Salt Lamp. Questions cost extra."]},
    {"id": "LC_WAREHOUSE_SIGN", "speaker": "NARRATION", "lines": ["Crown seal over the lock. Seized goods.", "The side door has a cheaper lock than the front."]},
    {"id": "LC_NOTES_CHEST", "speaker": "NARRATION", "lines": ["A scholar's satchel, half under a crate.", "The notes are inside."]},
    {"id": "VM_HANDOFF_GATE", "speaker": "NARRATION", "lines": ["The west gate stands open past sundown.", "The hills are a day's walk out."]},
    {"id": "CH3_SAVE", "speaker": "NARRATION", "lines": ["(The night is quiet. A good place to stop.)"]},
]

def q(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'

out = []
out.append('/// scr_dialogue_data_ch3 — Chapter 3 dialogue nodes, keyed by the line ids in')
out.append('/// docs/story/CHAPTER3_SCRIPT.md (approved by Kevin, Nov 14 2026, 3:53 PM ET). Text is verbatim.')
out.append('/// GENERATED by tools/gen_ch3_dialogue.py — edit the script and re-run, do not hand-edit.')
out.append('/// Speaker "" is NARRATION. The last block holds the wiring pass\'s placeholder lines (not in the script).')
out.append("")
out.append("function scr_ch3_dialogue_node(_id) {")
out.append("    switch (_id) {")
seen = set()
for n in nodes + [dict(e, extra=True) for e in EXTRA]:
    if n["id"] in seen or not n["lines"]:
        continue
    seen.add(n["id"])
    sp = "" if n["speaker"] == "NARRATION" else n["speaker"]
    lines = n["lines"]
    if n["id"] == "SL_PARCEL_02":
        lines = ["Accept?"]  # [Yes] [No] become a real choice (scr_ch3_parcel_offer)
    tag = "  // PLACEHOLDER (wiring pass, not in the script)" if n.get("extra") else ""
    out.append("        case %s:%s" % (q(n["id"]), tag))
    out.append("            return { id: %s, speaker: %s, lines: [%s] };" % (q(n["id"]), q(sp), ", ".join(q(l) for l in lines)))
out.append("    }")
out.append("    return undefined;")
out.append("}")
out.append("")
open(OUT, "w", encoding="utf-8").write("\n".join(out))
print("wrote", OUT, len(seen), "nodes")
