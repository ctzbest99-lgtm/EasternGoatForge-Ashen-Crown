def T(tx, ty):
    return tx * 16 + 8, ty * 16 + 16


class Grid:
    def __init__(self, w, h, fill=0):
        self.w, self.h = w, h
        self.d = [[fill] * w for _ in range(h)]

    def set(self, x, y, v):
        if 0 <= x < self.w and 0 <= y < self.h:
            self.d[y][x] = v

    def rect(self, x0, y0, x1, y1, v):
        for y in range(y0, y1 + 1):
            for x in range(x0, x1 + 1):
                self.set(x, y, v)

    def gml(self):
        rows = []
        for y in range(self.h):
            rows.append('            ' + ', '.join(str(t) for t in self.d[y]) + ',')
        return '\n'.join(rows).rstrip(',')


def emit_room(fn_name, w, h, ground, decor, overhead, coll, note):
    short = fn_name.replace("scr_build_", "")
    body = []
    body.append(f'/// {fn_name}(): fills its room ({w}x{h} tiles) from embedded data. {note}')
    body.append('/// Call from the room\'s Creation Code. Generated by tools/gen_ch5_rooms.py. Uses the ts_garrison tileset.')
    body.append(f'function {fn_name}() {{')
    body.append(f'    scr_gr_prepare_layers({w}, {h});')
    body.append(f'    scr_map_build_from_arrays(scr_{short}_data(), {w}, {h});')
    body.append(f'    scr_map_spawn_markers(scr_wf_filter_markers(scr_{short}_markers()));')
    body.append('    scr_map_enable_camera(320, 180);')
    body.append('    scr_camera_follow_player();')
    body.append('}')
    body.append('')
    body.append(f'function scr_{short}_data() {{')
    body.append('    return {')
    for key, g in (('ground', ground), ('decor', decor), ('overhead', overhead), ('collision', coll)):
        body.append(f'        {key}: [')
        body.append(g.gml())
        body.append('        ],')
    body.append('    };')
    body.append('}')
    return '\n'.join(body) + '\n'


def emit_markers(fn, w, h, markers, note):
    body = []
    body.append(f'/// {fn}() -> array of marker structs ({w}x{h} tiles). {note}')
    body.append('/// Generated by tools/gen_ch5_rooms.py. Extra keys as in scr_wf_markers_data (Chapter 2).')
    body.append(f'function {fn}() {{')
    body.append('    return [')
    for m in markers:
        parts = []
        for k, v in m.items():
            if isinstance(v, str):
                parts.append(f'{k}: "{v}"')
            elif isinstance(v, bool):
                parts.append(f'{k}: {"true" if v else "false"}')
            elif isinstance(v, list):
                items = []
                for x in v:
                    if isinstance(x, dict):
                        items.append('{ ' + ', '.join(
                            f'{ik}: "{iv}"' if isinstance(iv, str) else f'{ik}: {iv}'
                            for ik, iv in x.items()) + ' }')
                    elif isinstance(x, str):
                        items.append(f'"{x}"')
                    else:
                        items.append(str(x))
                parts.append(f'{k}: [{", ".join(items)}]')
            else:
                parts.append(f'{k}: {v}')
        body.append('        { ' + ', '.join(parts) + ' },')
    body.append('    ];')
    body.append('}')
    return '\n'.join(body) + '\n'


def npc(name, tx, ty, npc_id, speaker, script, sprite, facing='down', extra=None):
    m = {'type': 'npc', 'name': name, 'tile_x': tx, 'tile_y': ty, 'x': T(tx, ty)[0], 'y': T(tx, ty)[1],
         'npc_id': npc_id, 'speaker': speaker, 'script_id': script, 'sprite': sprite,
         'hostile': False, 'facing': facing}
    if extra:
        m.update(extra)
    return m


def extra(name, tx, ty, sprite, note):
    return {'type': 'extra', 'name': name, 'tile_x': tx, 'tile_y': ty, 'x': T(tx, ty)[0], 'y': T(tx, ty)[1],
            'sprite': sprite, 'note': note}


