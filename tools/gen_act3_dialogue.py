#!/usr/bin/env python3
"""Generate scr_dialogue_data_ch7 and scr_dialogue_data_ch8 from their chapter scripts.

Same parser and output shape as tools/gen_ch6_dialogue.py: every **ID** · Speaker line with
> quotes under it becomes one node (text verbatim), NARRATION becomes speaker "".
Each chapter's wiring-only lines are in EXTRA. Also writes the gamemaker mirrors and
registers the scripts in AshenCrown.yyp. Run from the repo root:
    python3 tools/gen_act3_dialogue.py
"""
import json, os, re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
GM = os.path.join(ROOT, 'gamemaker')

HDR = re.compile(r'^(?:.*?[,—] )?\*\*([A-Z][A-Z0-9_]+)\*\*\s*·\s*(.+?):?$')

CHAPTERS = [
    ('7', 'CHAPTER7_SCRIPT.md', 'scr_dialogue_data_ch7', 'Chapter 7', [
        {"id": "SH_BASIN_R1", "speaker": "NARRATION",
         "lines": ["The basin is dry, and the stone under the lip is worn smooth."]},
        {"id": "LT_MEET_R1", "speaker": "NARRATION",
         "lines": ["They are still standing where they were, facing the shrine."]},
        {"id": "TT_MEET_R1", "speaker": "Berrin",
         "lines": ["I've said what I came to say. Go on to the glade."]},
        {"id": "MT_FIGHT_01", "speaker": "NARRATION",
         "lines": ["The clearing is smaller than it was."]},
        {"id": "MT_FIGHT_02", "speaker": "SYSTEM",
         "lines": ["The Blackwood Matriarch. Boss."]},
        {"id": "CH7_LOCKED_GLADE", "speaker": "NARRATION",
         "lines": ["Berrin is still standing where the trees start. He came this far."]},
        {"id": "CH7_LOCKED_DOORS", "speaker": "NARRATION",
         "lines": ["The thing in the clearing is between the party and the far edge."]},
    ]),
    ('8', 'CHAPTER8_SCRIPT.md', 'scr_dialogue_data_ch8', 'Chapter 8', [
        {"id": "DW_SENT_R1", "speaker": "NARRATION",
         "lines": ["The sentinel has not moved. The litter is still swept to the sides."]},
        {"id": "DW_FIGHT_01", "speaker": "NARRATION",
         "lines": ["The Warden steps out of the doorway it has been filling."]},
        {"id": "DW_FIGHT_02", "speaker": "SYSTEM",
         "lines": ["The Door Warden. Boss."]},
    ]),
]


def q(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def parse(path):
    nodes, cur = [], None
    for line in open(path, encoding='utf-8').read().split('\n'):
        m = HDR.match(line)
        if m:
            sp = re.sub(r'\*\*\[.*$', '', m.group(2)).strip()
            sp = re.sub(r'\*\(.*?\)\*', '', sp).strip(' *')
            cur = {"id": m.group(1), "speaker": sp, "lines": []}
            nodes.append(cur)
            continue
        if cur is None:
            continue
        if line.startswith('>'):
            t = line[1:].strip()
            if t:
                cur["lines"].append(t)
        elif line.strip() and cur["lines"]:
            cur = None
    return nodes


def build(chapter, script, name, label, extra):
    nodes = parse(os.path.join(ROOT, 'docs/story', script)) + [dict(e, extra=True) for e in extra]
    out = [
        f'/// {name} — {label} dialogue nodes, keyed by the line ids in',
        f'/// docs/story/{script} (built Nov 16 2026). Text is verbatim.',
        '/// GENERATED by tools/gen_act3_dialogue.py — edit the script and re-run, do not hand-edit.',
        '/// Speaker "" is NARRATION. The last block holds wiring-only placeholder lines.',
        '',
        'function scr_%s_dialogue_node(_id) {' % name.replace('scr_dialogue_data_', ''),
        '    switch (_id) {',
    ]
    seen = set()
    for n in nodes:
        if n["id"] in seen or not n["lines"]:
            continue
        seen.add(n["id"])
        sp = "" if n["speaker"] == "NARRATION" else n["speaker"]
        tag = "  // PLACEHOLDER (wiring pass, not in the script)" if n.get("extra") else ""
        out.append("        case %s:%s" % (q(n["id"]), tag))
        out.append("            return { id: %s, speaker: %s, lines: [%s] };" % (
            q(n["id"]), q(sp), ", ".join(q(l) for l in n["lines"])))
    out += ["    }", "    return undefined;", "}", ""]
    text = "\n".join(out)

    gml = os.path.join(ROOT, 'game/scripts', name + '.gml')
    with open(gml, 'w', encoding='utf-8', newline='\n') as f:
        f.write(text)
    gdir = os.path.join(GM, 'scripts', name)
    os.makedirs(gdir, exist_ok=True)
    with open(os.path.join(gdir, name + '.gml'), 'w', encoding='utf-8', newline='\n') as f:
        f.write(text)
    with open(os.path.join(gdir, name + '.yy'), 'w', encoding='utf-8', newline='\n') as f:
        json.dump({
            "$GMScript": "v1", "%Name": name, "isCompatibility": False, "isDnD": False,
            "name": name, "parent": {"name": "scripts", "path": "folders/scripts.yy"},
            "resourceType": "GMScript", "resourceVersion": "2.0",
        }, f, indent=2)
        f.write('\n')

    yyp_path = os.path.join(GM, 'AshenCrown.yyp')
    yyp = open(yyp_path, encoding='utf-8').read()
    if '"name":"%s"' % name not in yyp:
        anchor = ('    {\n      "id":{\n        "name":"rm_hollow_approach",\n'
                  '        "path":"rooms/rm_hollow_approach/rm_hollow_approach.yy",\n      },\n    },\n')
        block = ('    {\n      "id":{\n        "name":"%s",\n        "path":"scripts/%s/%s.yy",\n      },\n    },\n'
                 % (name, name, name))
        assert anchor in yyp
        yyp = yyp.replace(anchor, block + anchor, 1)
        with open(yyp_path, 'w', encoding='utf-8', newline='\n') as f:
            f.write(yyp)
    print('wrote', gml, len(seen), 'nodes')


for chapter, script, name, label, extra in CHAPTERS:
    build(chapter, script, name, label, extra)
