#!/usr/bin/env python3
"""Generate Rimehold's armoury room and its GameMaker resources.

Act VIII is not written, so this is a functional blockout of the one location the
equipment pass needs: the Rimehold armoury that sells the tier-VIII shelf. It is a
small snow courtyard with a stone-faced armoury, a counter, racks and the armourer.
The room is gated on `flag_act4_complete`, the same provisional lock the Ashlands
outpost uses, so the tier is reachable once `scr_story_act()` reaches 8.

Emits, into game/scripts/ (and the gamemaker mirrors):
  scr_build_rimehold.gml
  scr_rimehold_markers_data.gml
and, into gamemaker/rooms/:
  rm_rimehold/ (.yy + RoomCreationCode.gml)

Registers the scripts and room in AshenCrown.yyp (idempotent). Room helpers come
from tools/gen_ch6_rooms.py, as with the Ashlands generator.

Run from the repo root:
    python3 tools/gen_rimehold_room.py
"""
import json
import os
import random

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..'))
SCR = os.path.join(ROOT, 'game', 'scripts')
GM = os.path.join(ROOT, 'gamemaker')
RM = os.path.join(GM, 'rooms')

# Load the shared room helpers without running the Blackwood room bodies.
_src = open(os.path.join(ROOT, 'tools', 'gen_ch6_rooms.py'), encoding='utf-8').read()
_helpers = _src[:_src.index('# ================================================================ rm_blackwood_deep')]
_ns = {'__file__': os.path.join(ROOT, 'tools', 'gen_ch6_rooms.py'), '__name__': 'gen_ch6_helpers'}
exec(compile(_helpers, 'gen_ch6_rooms.py', 'exec'), _ns)
T = _ns['T']; Grid = _ns['Grid']
marker_room_yy = _ns['marker_room_yy']; npc = _ns['npc']

# ts_blackwood/ts_zone1 ids. The snow rows are part of ts_zone1 (0-799), which
# ts_blackwood copies verbatim; the room switches the five layers to ts_blackwood.
SNOW = [270, 271]                    # the pale end of the snow ramp
STONE = [62, 63]                     # packed grey stone, not the grass end
CAP = [115, 116, 117, 118]
FACE = [131, 132, 133, 134]
COUNTER = [728, 729, 730]
RACK = 159
BRAZIER = 155
ROCK = 339


def emit_room(fn_name, w, h, ground, decor, overhead, coll, note):
    short = fn_name.replace("scr_build_", "")
    body = []
    body.append(f'/// {fn_name}(): fills its room ({w}x{h} tiles) from embedded data. {note}')
    body.append("/// Call from the room's Creation Code. Generated by tools/gen_rimehold_room.py. "
                "Uses the ts_blackwood tileset; its rows 0-49 are ts_zone1, including the snow tiles.")
    body.append(f'function {fn_name}() {{')
    body.append(f'    scr_bw_prepare_layers({w}, {h});')
    body.append(f'    scr_map_build_from_arrays(scr_{short}_data(), {w}, {h});')
    body.append(f'    scr_map_spawn_markers(scr_wf_filter_markers(scr_{short}_markers()));')
    body.append('    scr_map_enable_camera(320, 180);')
    body.append('    scr_camera_follow_player();')
    body.append('}')
    body.append('')
    body.append(f'function scr_{short}_data() {{')
    body.append('    return {')
    for key, g in (('ground', ground), ('decor', decor), ('overhead', overhead), ('collision', coll)):
        body.append(f'        {key}: [')
        body.append(g.gml())
        body.append('        ],')
    body.append('    };')
    body.append('}')
    return '\n'.join(body) + '\n'


def emit_markers(fn, w, h, markers, note):
    body = []
    body.append(f'/// {fn}() -> array of marker structs ({w}x{h} tiles). {note}')
    body.append('/// Generated by tools/gen_rimehold_room.py. Extra keys as in scr_wf_markers_data (Chapter 2).')
    body.append(f'function {fn}() {{')
    body.append('    return [')
    for m in markers:
        parts = []
        for k, v in m.items():
            if isinstance(v, str):
                parts.append(f'{k}: "{v}"')
            elif isinstance(v, bool):
                parts.append(f'{k}: {"true" if v else "false"}')
            elif isinstance(v, list):
                items = []
                for x in v:
                    items.append(f'"{x}"' if isinstance(x, str) else str(x))
                parts.append(f'{k}: [{", ".join(items)}]')
            else:
                parts.append(f'{k}: {v}')
        body.append('        { ' + ', '.join(parts) + ' },')
    body.append('    ];')
    body.append('}')
    return '\n'.join(body) + '\n'


random.seed(20261128)
W, H = 24, 16
g, d, o, c = Grid(W, H), Grid(W, H), Grid(W, H), Grid(W, H)

# Snow courtyard; the path and the armoury floor are packed stone.
for y in range(H):
    for x in range(W):
        g.set(x, y, random.choice(SNOW))
for y in range(5, 15):
    for x in (10, 11, 12, 13):
        g.set(x, y, random.choice(STONE))
for y in range(4, 8):
    for x in range(7, 18):
        g.set(x, y, random.choice(STONE))

# Perimeter wall, with the south gate left open.
for x in range(W):
    for y in (0, 1):
        d.set(x, y, random.choice(CAP if y == 0 else FACE)); c.set(x, y, 1)
    if x < 10 or x > 13:
        d.set(x, 15, random.choice(CAP)); c.set(x, 15, 1)
for y in range(2, 15):
    for x in (0, 1, 22, 23):
        d.set(x, y, random.choice(FACE)); c.set(x, y, 1)

# The armoury's stone face and its counter. The armourer stands between them,
# reachable from the courtyard side.
for y in (2, 3):
    for x in range(7, 18):
        d.set(x, y, random.choice(CAP if y == 2 else FACE)); c.set(x, y, 1)
for i, x in enumerate(range(9, 16)):
    d.set(x, 5, COUNTER[i % 3]); c.set(x, 5, 1)
for x in (7, 17):
    d.set(x, 5, RACK); c.set(x, 5, 1)
for x in (8, 16):
    d.set(x, 8, BRAZIER); c.set(x, 8, 1)

# Rock and ice at the courtyard edges.
for (x, y) in ((4, 12), (19, 12), (4, 4), (19, 4)):
    d.set(x, y, ROCK); c.set(x, y, 1)

markers = [
    {'type': 'player_spawn', 'name': 'from_overworld', 'tile_x': 12, 'tile_y': 14,
     'x': T(12, 14)[0], 'y': T(12, 14)[1], 'facing': 'up',
     'note': 'Arrive at the Rimehold armoury from the overworld.'},
    {'type': 'zone_exit', 'name': 'to_overworld', 'tile_x': 12, 'tile_y': 15,
     'x': T(12, 15)[0], 'y': T(12, 15)[1], 'target_room': 'rm_overworld',
     'target_spawn': 'rimehold', 'w': 3, 'h': 1,
     'note': 'Back out to the Rimehold overworld entrance.'},
    npc('rimehold_armourer', 12, 6, 'villager', 'Armourer', 'RIMHOLD_ARMOURER',
        'spr_traveler_ow16_idle_left', 'down',
        {'note': 'The Rimehold armourer: the Act VIII shelf (shop_rimehold_armoury). '
                 'Placeholder sprite; the tier is gated by scr_story_act().'}),
    {'type': 'lore', 'name': 'rimehold_armoury_sign', 'tile_x': 19, 'tile_y': 8,
     'x': T(19, 8)[0], 'y': T(19, 8)[1],
     'lines': ['Rimehold keeps what Rimehold needs. The rest goes south with the road.',
               'The steel on the rack is older than the wall. It has outlasted the cold.'],
     'note': 'Look text at the armoury. No new lore: the shop and the settlement only.'},
]

files = {
    'scr_build_rimehold.gml': emit_room(
        'scr_build_rimehold', W, H, g, d, o, c,
        'The Rimehold armoury: a snow courtyard, the stone-faced shop and the tier-VIII shelf. '
        'Act VIII region, built ahead of its act as a balance/data stopgap.'),
    'scr_rimehold_markers_data.gml': emit_markers(
        'scr_rimehold_markers', W, H, markers,
        'Rimehold armoury markers (Act VIII region; built ahead of its act).'),
}

write_list = []
for fn, body_text in files.items():
    text = '/// Generated by tools/gen_rimehold_room.py — do not hand-edit.\n\n' + body_text
    with open(os.path.join(SCR, fn), 'w', encoding='utf-8', newline='\n') as f:
        f.write(text)
    write_list.append(fn)
    print('wrote', fn)

room_name = 'rm_rimehold'
folder = os.path.join(RM, room_name)
os.makedirs(folder, exist_ok=True)
with open(os.path.join(folder, room_name + '.yy'), 'w', encoding='utf-8', newline='\n') as f:
    json.dump(marker_room_yy(room_name, W, H, 12, 14), f, indent=2)
    f.write('\n')
with open(os.path.join(folder, 'RoomCreationCode.gml'), 'w', encoding='utf-8', newline='\n') as f:
    f.write('scr_build_rimehold();\n')
print('wrote', room_name)


def mirror_script(fn):
    gdir = os.path.join(GM, 'scripts', fn[:-4])
    os.makedirs(gdir, exist_ok=True)
    with open(os.path.join(gdir, fn), 'w', encoding='utf-8', newline='\n') as f:
        f.write(open(os.path.join(SCR, fn), encoding='utf-8').read())
    with open(os.path.join(gdir, fn[:-4] + '.yy'), 'w', encoding='utf-8', newline='\n') as f:
        json.dump({
            "$GMScript": "v1", "%Name": fn[:-4], "isCompatibility": False, "isDnD": False,
            "name": fn[:-4], "parent": {"name": "scripts", "path": "folders/scripts.yy"},
            "resourceType": "GMScript", "resourceVersion": "2.0",
        }, f, indent=2)
        f.write('\n')


for fn in write_list:
    mirror_script(fn)

yyp_path = os.path.join(GM, 'AshenCrown.yyp')
yyp = open(yyp_path, encoding='utf-8').read()
anchor = ('    {\n      "id":{\n        "name":"scr_build_ashlands_breach",\n'
          '        "path":"scripts/scr_build_ashlands_breach/scr_build_ashlands_breach.yy",\n      },\n    },\n')
room_anchor = ('    {\n      "id":{\n        "name":"rm_ashlands_breach",\n'
               '        "path":"rooms/rm_ashlands_breach/rm_ashlands_breach.yy",\n      },\n    },\n')
added = []
for fn in write_list:
    name = fn[:-4]
    if '"name":"%s"' % name in yyp:
        continue
    block = ('    {\n      "id":{\n        "name":"%s",\n        "path":"scripts/%s/%s.yy",\n      },\n    },\n'
             % (name, name, name))
    yyp = yyp.replace(anchor, block + anchor, 1)
    added.append(name)
if '"name":"%s"' % room_name not in yyp:
    block = ('    {\n      "id":{\n        "name":"%s",\n        "path":"rooms/%s/%s.yy",\n      },\n    },\n'
             % (room_name, room_name, room_name))
    yyp = yyp.replace(room_anchor, room_anchor + block, 1)
    added.append(room_name)
    start = yyp.index('"RoomOrderNodes":[')
    end = yyp.index('\n  ],', start)
    node = ('    {\n      "roomId":{\n        "name":"%s",\n        "path":"rooms/%s/%s.yy",\n      },\n    },\n'
            % (room_name, room_name, room_name))
    yyp = yyp[:end] + '\n' + node.rstrip('\n') + yyp[end:]
if added:
    with open(yyp_path, 'w', encoding='utf-8', newline='\n') as f:
        f.write(yyp)
print('registered in yyp:', added if added else 'nothing new')
print('done')
