#!/usr/bin/env python3
"""Generate scr_dialogue_data_ch9 from docs/story/CHAPTER9_SCRIPT.md.

Same parser and output shape as tools/gen_ch6_dialogue.py and tools/gen_act3_dialogue.py: every
**ID** · Speaker line with > quotes under it becomes one node (text verbatim), NARRATION becomes
speaker "". The EXTRA block holds the repeat-talk and locked-road lines that only exist as
wiring, not as scripted scenes.

Writes game/scripts/scr_dialogue_data_ch9.gml, its gamemaker mirror + .yy, and registers the
script in AshenCrown.yyp (idempotent). Run from the repo root:
    python3 tools/gen_ch9_dialogue.py
"""
import json, os, re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
GM = os.path.join(ROOT, 'gamemaker')

HDR = re.compile(r'^(?:.*?[,—] )?\*\*([A-Z][A-Z0-9_]+)\*\*\s*·\s*(.+?):?$')

EXTRA = [
    {"id": "TN_BOARD_R1", "speaker": "NARRATION",
     "lines": ["The survey line is still on the board, and it still has no description."]},
    {"id": "VG_MEET_R1", "speaker": "Vell",
     "lines": ["The page is yours. I'd rather not discuss the drawer it came out of."]},
    {"id": "CL_WAIT_01", "speaker": "Nessa",
     "lines": ["The magistrate has the survey out. He's the one with the drawer."]},
    {"id": "CL_WAIT_02", "speaker": "Nessa",
     "lines": ["When you've got the page, come back. I'll still be here. I'm always here."]},
    {"id": "CL_CHOICE_R1", "speaker": "Nessa",
     "lines": ["I've said my piece. The page is where it is."]},
    {"id": "AL_WAIT_01", "speaker": "Alden",
     "lines": ["You've the look of people who found something and haven't decided what to do with it."]},
    {"id": "AL_WAIT_02", "speaker": "Alden",
     "lines": ["Go on. I'll be at this table. I'm very good at waiting in inns."]},
    {"id": "AL_MEET_R1", "speaker": "Alden",
     "lines": ["First light. I'll be at the gate with the horses, looking useless."]},
    {"id": "CH9_ROAD_01", "speaker": "NARRATION",
     "lines": ["The track south loses its gravel and becomes mud with a direction."]},
    {"id": "CH9_ROAD_02", "speaker": "Taren",
     "lines": ["That's a road the way a debt is a promise. Somebody's been paying to keep it walkable."]},
    {"id": "CH9_ROAD_03", "speaker": "Kael",
     "lines": ["Not yet. We finish the town first."]},
]


def q(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def parse(path):
    nodes, cur = [], None
    for line in open(path, encoding='utf-8').read().split('\n'):
        m = HDR.match(line)
        if m:
            sp = re.sub(r'\*\*\[.*$', '', m.group(2)).strip()
            sp = re.sub(r'\*\(.*?\)\*', '', sp).strip(' *')
            cur = {"id": m.group(1), "speaker": sp, "lines": []}
            nodes.append(cur)
            continue
        if cur is None:
            continue
        if line.startswith('>'):
            t = line[1:].strip()
            if t:
                cur["lines"].append(t)
        elif line.strip() and cur["lines"]:
            cur = None
    return nodes


def build(script, name, label, extra):
    nodes = parse(os.path.join(ROOT, 'docs/story', script)) + [dict(e, extra=True) for e in extra]
    out = [
        f'/// {name} — {label} dialogue nodes, keyed by the line ids in',
        f'/// docs/story/{script} (built Nov 16 2026 from the approved Act IV decisions).',
        '/// GENERATED by tools/gen_ch9_dialogue.py — edit the script and re-run, do not hand-edit.',
        '/// Speaker "" is NARRATION. The last block holds wiring-only placeholder lines.',
        '',
        'function scr_%s_dialogue_node(_id) {' % name.replace('scr_dialogue_data_', ''),
        '    switch (_id) {',
    ]
    seen = set()
    for n in nodes:
        if n["id"] in seen or not n["lines"]:
            continue
        seen.add(n["id"])
        sp = "" if n["speaker"] == "NARRATION" else n["speaker"]
        tag = "  // PLACEHOLDER (wiring pass, not in the script)" if n.get("extra") else ""
        out.append("        case %s:%s" % (q(n["id"]), tag))
        out.append("            return { id: %s, speaker: %s, lines: [%s] };" % (
            q(n["id"]), q(sp), ", ".join(q(l) for l in n["lines"])))
    out += ["    }", "    return undefined;", "}", ""]
    text = "\n".join(out)

    gml = os.path.join(ROOT, 'game/scripts', name + '.gml')
    with open(gml, 'w', encoding='utf-8', newline='\n') as f:
        f.write(text)
    gdir = os.path.join(GM, 'scripts', name)
    os.makedirs(gdir, exist_ok=True)
    with open(os.path.join(gdir, name + '.gml'), 'w', encoding='utf-8', newline='\n') as f:
        f.write(text)
    with open(os.path.join(gdir, name + '.yy'), 'w', encoding='utf-8', newline='\n') as f:
        json.dump({
            "$GMScript": "v1", "%Name": name, "isCompatibility": False, "isDnd": False,
            "name": name, "parent": {"name": "scripts", "path": "folders/scripts.yy"},
            "resourceType": "GMScript", "resourceVersion": "2.0",
        }, f, indent=2)
        f.write('\n')

    yyp_path = os.path.join(GM, 'AshenCrown.yyp')
    yyp = open(yyp_path, encoding='utf-8').read()
    if '"name":"%s"' % name not in yyp:
        anchor = ('    {\n      "id":{\n        "name":"rm_hollow_approach",\n'
                  '        "path":"rooms/rm_hollow_approach/rm_hollow_approach.yy",\n      },\n    },\n')
        block = ('    {\n      "id":{\n        "name":"%s",\n        "path":"scripts/%s/%s.yy",\n      },\n    },\n'
                 % (name, name, name))
        assert anchor in yyp
        yyp = yyp.replace(anchor, block + anchor, 1)
        with open(yyp_path, 'w', encoding='utf-8', newline='\n') as f:
            f.write(yyp)
    print('wrote', gml, len(seen), 'nodes')


build('CHAPTER9_SCRIPT.md', 'scr_dialogue_data_ch9', 'Chapter 9', EXTRA)
