#!/usr/bin/env python3
"""Generate scr_dialogue_data_ch5.gml from docs/story/CHAPTER5_SCRIPT.md.

Every **ID** · Speaker line with a > quote below it becomes one node (text verbatim).
NARRATION -> speaker "" (no name in the box), as in Chapters 1-4.

Also writes the gamemaker mirror (gamemaker/scripts/scr_dialogue_data_ch5/) and adds the
script to AshenCrown.yyp if it is not registered yet. Re-run after script edits:
    python3 tools/gen_ch5_dialogue.py
"""
import json, re, os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "docs/story/CHAPTER5_SCRIPT.md")
OUT = os.path.join(ROOT, "game/scripts/scr_dialogue_data_ch5.gml")
GM = os.path.join(ROOT, "gamemaker")
NAME = "scr_dialogue_data_ch5"

hdr = re.compile(r'^(?:.*?[,—] )?\*\*([A-Z][A-Z0-9_]+)\*\*\s*·\s*(.+?):?$')
nodes, cur = [], None
for line in open(SRC, encoding="utf-8").read().split("\n"):
    m = hdr.match(line)
    if m:
        sp = re.sub(r'\*\*\[.*$', '', m.group(2)).strip()
        sp = re.sub(r'\*\(.*?\)\*', '', sp).strip(' *')
        cur = {"id": m.group(1), "speaker": sp, "lines": []}
        nodes.append(cur)
        continue
    if cur is None:
        continue
    if line.startswith(">"):
        t = line[1:].strip()
        if t:
            cur["lines"].append(t)
    elif line.strip() and cur["lines"]:
        cur = None

# Lines the wiring needs that the script does not carry (repeat talk, gated doors, the
# choice prompt). Tagged PLACEHOLDER in the output; change freely.
EXTRA = [
    {"id": "BG_NOTICE_R1", "speaker": "NARRATION",
     "lines": ["The deserter notice is still the freshest thing on the board."]},
    {"id": "BG_GATE_R1", "speaker": "Sergeant",
     "lines": ["Commander's orders were to hold the post.",
               "Nobody said anything about holding it well."]},
    {"id": "BG_YARD_R1", "speaker": "NARRATION",
     "lines": ["The yard has gone back to its work. Nobody is meeting your eye."]},
    {"id": "SR_MEET_R1", "speaker": "Sera",
     "lines": ["Ask the commander. He keeps the answers in a chest.",
               "I only know what he won't say out loud."]},
    {"id": "HL_INTRO_R1", "speaker": "Commander Hailen",
     "lines": ["You're still standing in my yard.",
               "Say what you came to say."]},
    {"id": "BG_KEEP_LOCKED", "speaker": "NARRATION",
     "lines": ["The office door is barred from the inside.",
               "Nobody is opening it while the commander is standing."]},
    {"id": "BW_LEAD_R1", "speaker": "NARRATION",
     "lines": ["The ledger is open where you left it.",
               "Some of the crossed-out names have dates beside them."]},
    {"id": "SR_STAKE_R1", "speaker": "Sera",
     "lines": ["Ask me about the road.",
               "The road I'll answer for."]},
    {"id": "CH5_HANDOFF_LOCKED", "speaker": "NARRATION",
     "lines": ["Not yet. The lead is still in the commander's office."]},
]


def q(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


out = []
out.append('/// scr_dialogue_data_ch5 — Chapter 5 dialogue nodes, keyed by the line ids in')
out.append('/// docs/story/CHAPTER5_SCRIPT.md (approved Nov 16 2026). Text is verbatim.')
out.append('/// GENERATED by tools/gen_ch5_dialogue.py — edit the script and re-run, do not hand-edit.')
out.append('/// Speaker "" is NARRATION. The last block holds the wiring pass\'s placeholder lines (not in the script).')
out.append("")
out.append("function scr_ch5_dialogue_node(_id) {")
out.append("    switch (_id) {")
seen = set()
for n in nodes + [dict(e, extra=True) for e in EXTRA]:
    if n["id"] in seen or not n["lines"]:
        continue
    seen.add(n["id"])
    sp = "" if n["speaker"] == "NARRATION" else n["speaker"]
    tag = "  // PLACEHOLDER (wiring pass, not in the script)" if n.get("extra") else ""
    out.append("        case %s:%s" % (q(n["id"]), tag))
    out.append("            return { id: %s, speaker: %s, lines: [%s] };" % (
        q(n["id"]), q(sp), ", ".join(q(l) for l in n["lines"])))
out.append("    }")
out.append("    return undefined;")
out.append("}")
out.append("")
text = "\n".join(out)
with open(OUT, "w", encoding="utf-8", newline="\n") as f:
    f.write(text)

# gamemaker mirror: identical .gml + the resource .yy
gdir = os.path.join(GM, "scripts", NAME)
os.makedirs(gdir, exist_ok=True)
with open(os.path.join(gdir, NAME + ".gml"), "w", encoding="utf-8", newline="\n") as f:
    f.write(text)
with open(os.path.join(gdir, NAME + ".yy"), "w", encoding="utf-8", newline="\n") as f:
    json.dump({
        "$GMScript": "v1", "%Name": NAME, "isCompatibility": False, "isDnD": False,
        "name": NAME, "parent": {"name": "scripts", "path": "folders/scripts.yy"},
        "resourceType": "GMScript", "resourceVersion": "2.0",
    }, f, indent=2)
    f.write("\n")

# yyp registration (idempotent)
yyp_path = os.path.join(GM, "AshenCrown.yyp")
yyp = open(yyp_path, encoding="utf-8").read()
if '"name":"%s"' % NAME not in yyp:
    anchor = ('    {\n      "id":{\n        "name":"rm_hollow_approach",\n'
              '        "path":"rooms/rm_hollow_approach/rm_hollow_approach.yy",\n      },\n    },\n')
    assert anchor in yyp, "yyp anchor for the resource list not found"
    block = ('    {\n      "id":{\n        "name":"%s",\n'
             '        "path":"scripts/%s/%s.yy",\n      },\n    },\n') % (NAME, NAME, NAME)
    yyp = yyp.replace(anchor, block + anchor, 1)
    with open(yyp_path, "w", encoding="utf-8", newline="\n") as f:
        f.write(yyp)
    print("registered", NAME, "in the yyp")
else:
    print(NAME, "already registered")

print("wrote", OUT, len(seen), "nodes")
