#!/usr/bin/env python3
"""Generate game/scripts/scr_dialogue_data_ch4.gml from docs/story/CHAPTER4_SCRIPT.md.

Every **ID** · Speaker line with a > quote below it becomes one node (text verbatim).
NARRATION -> speaker "" (no name in the box), as in Chapters 1-3. Re-run after edits:
    python3 tools/gen_ch4_dialogue.py
"""
import re, os
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "docs/story/CHAPTER4_SCRIPT.md")
OUT = os.path.join(ROOT, "game/scripts/scr_dialogue_data_ch4.gml")

hdr = re.compile(r'^(?:.*?[,—] )?\*\*([A-Z][A-Z0-9_]+)\*\*\s*·\s*(.+?):?$')
nodes, cur = [], None
for line in open(SRC, encoding="utf-8").read().split("\n"):
    m = hdr.match(line)
    if m:
        sp = re.sub(r'\*\*\[.*$', '', m.group(2)).strip()
        sp = re.sub(r'\*\(.*?\)\*', '', sp).strip(' *')
        cur = {"id": m.group(1), "speaker": sp, "lines": []}
        nodes.append(cur)
        continue
    if cur is None:
        continue
    if line.startswith(">"):
        t = line[1:].strip()
        if t:
            cur["lines"].append(t)
    elif line.strip() and cur["lines"]:
        cur = None

# Lines the wiring pass needs that the script does not carry (inspect spots, quiet save
# prompt, repeat talk). Clearly tagged; change freely.
EXTRA = [
    {"id": "HS_SAVE", "speaker": "NARRATION",
     "lines": ["(The hollow is quiet behind you. A good place to stop.)"]},
    {"id": "HS_SHEP_R1", "speaker": "NARRATION",
     "lines": ["The shepherd has already turned back toward the road."]},
    {"id": "SW_LOCKED", "speaker": "NARRATION",
     "lines": ["The inner door is shut.", "The scholar by the shelves is watching you."]},
    {"id": "SW_DOOR_AFTER", "speaker": "NARRATION",
     "lines": ["The inner door stands shut. Whatever is behind it can wait."]},
]


def q(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


out = []
out.append('/// scr_dialogue_data_ch4 — Chapter 4 dialogue nodes, keyed by the line ids in')
out.append('/// docs/story/CHAPTER4_SCRIPT.md (approved Nov 15 2026). Text is verbatim.')
out.append('/// GENERATED by tools/gen_ch4_dialogue.py — edit the script and re-run, do not hand-edit.')
out.append('/// Speaker "" is NARRATION. The last block holds the wiring pass\'s placeholder lines (not in the script).')
out.append("")
out.append("function scr_ch4_dialogue_node(_id) {")
out.append("    switch (_id) {")
seen = set()
for n in nodes + [dict(e, extra=True) for e in EXTRA]:
    if n["id"] in seen or not n["lines"]:
        continue
    seen.add(n["id"])
    sp = "" if n["speaker"] == "NARRATION" else n["speaker"]
    tag = "  // PLACEHOLDER (wiring pass, not in the script)" if n.get("extra") else ""
    out.append("        case %s:%s" % (q(n["id"]), tag))
    out.append("            return { id: %s, speaker: %s, lines: [%s] };" % (
        q(n["id"]), q(sp), ", ".join(q(l) for l in n["lines"])))
out.append("    }")
out.append("    return undefined;")
out.append("}")
out.append("")
open(OUT, "w", encoding="utf-8").write("\n".join(out))
print("wrote", OUT, len(seen), "nodes")
