#!/usr/bin/env python3
"""Generate game/scripts/scr_dialogue_data_ch2.gml from docs/story/CHAPTER2_SCRIPT.md.

Every **ID** · Speaker line with a > quote below it becomes one node (text verbatim).
NARRATION -> speaker "" (no name in the box), as in Chapter 1. Re-run after script edits:
    python3 tools/gen_ch2_dialogue.py
"""
import re, json, os
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "docs/story/CHAPTER2_SCRIPT.md")
OUT = os.path.join(ROOT, "game/scripts/scr_dialogue_data_ch2.gml")

hdr = re.compile(r'^(?:.*?[,—] )?\*\*([A-Z][A-Z0-9_]+)\*\*\s*·\s*(.+?):?$')
nodes, cur = [], None
for line in open(SRC, encoding="utf-8").read().split("\n"):
    m = hdr.match(line)
    if m:
        sp = re.sub(r'\*\*\[.*$', '', m.group(2)).strip()
        sp = re.sub(r'\*\(.*?\)\*', '', sp).strip(' *')
        cur = {"id": m.group(1), "speaker": sp, "lines": []}
        nodes.append(cur)
        continue
    if cur is None:
        continue
    if line.startswith(">"):
        t = line[1:].strip()
        if t:
            cur["lines"].append(t)
    elif line.strip() and cur["lines"]:
        cur = None

# Portrait expressions (Design's sets: bram shaken/afraid/grateful, oda worried/pleading/relieved,
# perrin neutral/grim/warm, len neutral/nervous/smile, taren neutral/determined/wry,
# reeve_calder neutral/stern/weary). Anything not listed uses the speaker's default.
EXPR = {
    "WF_ODA_A1": "pleading", "WF_ODA_A3_YES": "worried", "WF_ODA_A4_NO": "worried", "WF_ODA_B1": "relieved",
    "WF_ODA_B3": "shaken",
    "WF_TAVERN_A1": "grim", "WF_TAVERN_A3": "grim", "WF_TAVERN_B1": "warm",
    "WF_STORE_A1": "nervous", "WF_STORE_B1": "smile",
    "WF_GALLOWS_03": "determined", "WF_GALLOWS_06": "determined", "WF_GALLOWS_08": "determined",
    "WF_CALDER_INTRO_04": "determined", "WF_CALDER_INTRO_06": "determined", "WF_CALDER_DEFEAT_02": "determined",
    "WF_JOIN_01": "wry", "WF_JOIN_06": "determined", "WF_JOIN_07": "determined", "WF_JOIN_12": "determined",
    "WF_JOIN_R1": "wry", "WF_HANDOFF_01": "determined", "WF_HANDOFF_03": "determined",
    "WF_GALLOWS_01": "stern", "WF_GALLOWS_04": "stern", "WF_CALDER_INTRO_01": "stern", "WF_CALDER_INTRO_03": "stern",
    "WF_CALDER_INTRO_05": "stern", "WF_CALDER_INTRO_07": "stern", "WF_CALDER_PHASE2_01": "stern",
    "WF_CALDER_DEFEAT_01": "weary", "WF_CALDER_DEFEAT_03": "weary", "WF_CALDER_DEFEAT_05": "weary",
}
# Lines the map art pass wrote (not in the script). Kept so every marker resolves; change freely.
EXTRA = [
    {"id": "WF_STORE_SHUT", "speaker": "NARRATION", "lines": ["Shuttered and barred. Len isn't selling today."]},
    {"id": "WF_WEST_LOCKED", "speaker": "NARRATION", "lines": ["Crown checkpoint. West road closed by order of the Reeve."]},
    {"id": "WF_TAVERN_NOTICE", "speaker": "NARRATION", "lines": ["Chalked on a board: \"Rooms upstairs. Ask Perrin.\""]},
    {"id": "OW_MR_LOCKED", "speaker": "NARRATION", "lines": ["Crown checkpoint. No passage south without the Reeve's leave."]},
    {"id": "OW_MR_FORK_SIGN", "speaker": "NARRATION", "lines": ["South: Wrenfield and the Millhaven road."]},
    {"id": "CH2_TBC", "speaker": "NARRATION", "lines": ["To be continued."]},
]

def q(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'

out = []
out.append("/// scr_dialogue_data_ch2 — Chapter 2 dialogue nodes, keyed by the line ids in")
out.append("/// docs/story/CHAPTER2_SCRIPT.md (approved by Kevin at cc8faff). Text is verbatim.")
out.append("/// GENERATED by tools/gen_ch2_dialogue.py — edit the script and re-run, do not hand-edit.")
out.append("/// Speaker \"\" is NARRATION. `expr` picks the portrait expression (scr_ch1_portrait).")
out.append("/// The last block holds the map art pass's placeholder lines (not in the script).")
out.append("")
out.append("function scr_ch2_dialogue_node(_id) {")
out.append("    switch (_id) {")
seen = set()
for n in nodes + [dict(e, extra=True) for e in EXTRA]:
    if n["id"] in seen or not n["lines"]:
        continue
    seen.add(n["id"])
    sp = "" if n["speaker"] == "NARRATION" else n["speaker"]
    lines = n["lines"]
    if n["id"] == "WF_ODA_A2":
        lines = ["Accept?"]  # [Yes] [No] become a real choice (scr_ch2_oda_offer)
    expr = EXPR.get(n["id"], "")
    tag = "  // PLACEHOLDER (art pass, not in the script)" if n.get("extra") else ""
    e = (", expr: " + q(expr)) if expr else ""
    out.append("        case %s:%s" % (q(n["id"]), tag))
    out.append("            return { id: %s, speaker: %s, lines: [%s]%s };" % (q(n["id"]), q(sp), ", ".join(q(l) for l in lines), e))
out.append("    }")
out.append("    return undefined;")
out.append("}")
out.append("")
open(OUT, "w", encoding="utf-8").write("\n".join(out))
print("wrote", OUT, len(seen), "nodes")
