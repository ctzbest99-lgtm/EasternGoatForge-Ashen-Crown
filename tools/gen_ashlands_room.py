# Sanity: every spawn, exit and lore tile is walkable, and every exit target resolves to a
# spawn name in the room it goes to. This catches a moved marker before the game does.
names_by_room = {name: {m['name'] for m in body[6]} for name, body in ROOMS.items()}
for name, (w, h, ground, decor, overhead, coll, markers) in ROOMS.items():
    blocked = {(x, y) for y in range(h) for x in range(w) if coll.d[y][x]}
    for m in markers:
        tx, ty = m['tile_x'], m['tile_y']
        assert (tx, ty) not in blocked, '%s: %s tile (%d,%d) is blocked' % (name, m['name'], tx, ty)
        if m['type'] == 'zone_exit':
            target = m['target_room']
            if target not in ROOMS:
                continue  # rm_overworld is not generated here; audit_chapters checks its spawns
            spawn = m.get('target_spawn', '')
            assert spawn in names_by_room[target], \
                '%s: exit %s spawn %r missing from %s' % (name, m['name'], spawn, target)
    spawn = next(m for m in markers if m['type'] == 'player_spawn')
    seen = {(spawn['tile_x'], spawn['tile_y'])}
    queue = [(spawn['tile_x'], spawn['tile_y'])]
    while queue:
        x, y = queue.pop(0)
        for nx, ny in ((x + 1, y), (x - 1, y), (x, y + 1), (x, y - 1)):
            if 0 <= nx < w and 0 <= ny < h and (nx, ny) not in seen and (nx, ny) not in blocked:
                seen.add((nx, ny))
                queue.append((nx, ny))
    for m in markers:
        assert (m['tile_x'], m['tile_y']) in seen, \
            '%s: %s (%d,%d) is not reachable from %s' % (
                name, m['name'], m['tile_x'], m['tile_y'], spawn['name'])
    print('%s: reachability OK from %s to %d marker(s)' % (name, spawn['name'], len(markers)))

