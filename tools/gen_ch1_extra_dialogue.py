#!/usr/bin/env python3
"""Generates game/scripts/scr_dialogue_data_ch1_extra.gml.

Chapters 2-11 each have a generated dialogue data script. Chapter 1's data was built by
hand before the generators existed, and 22 scripted scenes never made it in: the signpost
lore, the Hunter's Camp (Old Hunter Renn's quest) and the Blackguard's phase lines. This
tool reads docs/story/CHAPTER1_SCRIPT.md and emits exactly the ids that appear in no
other dialogue data file, so re-running it after the script changes stays safe.
"""
import glob
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, 'game', 'scripts')
MD = os.path.join(ROOT, 'docs', 'story', 'CHAPTER1_SCRIPT.md')
OUT = os.path.join(SRC, 'scr_dialogue_data_ch1_extra.gml')

HDR = re.compile(r'^(?:.*?[,—] )?\*\*([A-Z][A-Z0-9_]+)\*\*\s*·\s*(.+?):?$')
ANNOT = re.compile(r'\*\s*\([^)]*\)\s*\*|\[[^\]]*\]|\([^)]*\)')


def speaker_of(raw):
    s = ANNOT.sub(' ', raw)
    s = s.replace('**', '').replace('*', ' ')
    s = name = re.sub(r'\s+', ' ', s).strip()
    if name.upper() == 'NARRATION':
        return ''
    return name


def parse():
    lines = open(MD, encoding='utf-8').read().split('\n')
    nodes = []
    i = 0
    while i < len(lines):
        m = HDR.match(lines[i])
        if not m:
            i += 1
            continue
        node_id, raw_speaker = m.group(1), m.group(2)
        body = []
        i += 1
        while i < len(lines) and lines[i].startswith('>'):
            body.append(lines[i][1:].strip())
            i += 1
        if body:
            nodes.append((node_id, speaker_of(raw_speaker), body))
    return nodes


def js(s):
    return s.replace('\\', '\\\\').replace('"', '\\"')


def main():
    have = set()
    for f in glob.glob(os.path.join(SRC, 'scr_dialogue_data*.gml')):
        if os.path.basename(f) == os.path.basename(OUT):
            continue
        have |= set(re.findall(r'case "([A-Z][A-Z0-9_]+)":', open(f, encoding='utf-8').read()))

    nodes = [n for n in parse() if n[0] not in have]
    out = [
        '/// scr_dialogue_data_ch1_extra — Chapter 1 lines that the hand-built',
        '/// scr_dialogue_data.gml never received: the signpost lore, the Hunter\'s Camp',
        '/// (Old Hunter Renn and Q_SIDE_RENN) and the Blackguard\'s phase narration.',
        '/// Text is verbatim from docs/story/CHAPTER1_SCRIPT.md.',
        '/// GENERATED by tools/gen_ch1_extra_dialogue.py — edit the script and re-run, do not hand-edit.',
        '',
        'function scr_ch1_extra_dialogue_node(_id) {',
        '    switch (_id) {',
    ]
    for node_id, speaker, body in nodes:
        body_s = ', '.join('"%s"' % js(b) for b in body)
        out.append('        case "%s":' % node_id)
        out.append('            return { id: "%s", speaker: "%s", lines: [%s] };'
                   % (node_id, js(speaker), body_s))
    out += [
        '    }',
        '    return undefined;',
        '}',
        '',
    ]
    open(OUT, 'w', encoding='utf-8').write('\n'.join(out))
    print('wrote %s: %d nodes' % (os.path.relpath(OUT, ROOT), len(nodes)))
    for node_id, _, _ in nodes:
        print('   ', node_id)


if __name__ == '__main__':
    main()
